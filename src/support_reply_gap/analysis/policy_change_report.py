"""D1b report: ratings around the reply-policy changes.

    python -m support_reply_gap.analysis.policy_change_report

Writes reports/policy_change.md and reports/policy_change.png from Postgres. Stars,
dates and reply status only: no labels, no API calls. The interpretation lives in the
README, where re-running cannot overwrite it.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from support_reply_gap.analysis.policy_change import (
    ALL,
    EVENTS,
    FIRST_MONTH,
    LAST_MONTH,
    REFERENCE_APP,
    WITHOUT_EDITED,
    load_monthly_input,
    monthly,
    period_table,
)
from support_reply_gap.analysis.policy_change_chart import APP_ORDER, plot_policy_change
from support_reply_gap.apps import by_key

ROOT = Path(__file__).resolve().parents[3]
REPORT_PATH = ROOT / "reports/policy_change.md"
CHART_PATH = ROOT / "reports/policy_change.png"


def fmt_mean(row: pd.Series) -> str:
    """'3.42 (3.21–3.63)'; a dash for an empty group."""
    if row["n"] == 0:
        return "–"
    return f"{row['mean_score']:.2f} ({row['low']:.2f}–{row['high']:.2f})"


def fmt_share(value: float, n: int) -> str:
    return "–" if n == 0 else f"{value:.0%}"


def events_text() -> str:
    lines = []
    for app, events in EVENTS.items():
        steps = ", ".join(f"{name} from {month}" for month, name in events)
        lines.append(f"- {by_key(app).label}: {steps}.")
    lines.append(f"- {by_key(REFERENCE_APP).label}: no change; a reference series, not a control.")
    return "\n".join(lines)


def period_markdown(periods: pd.DataFrame, version: str) -> str:
    ref = by_key(REFERENCE_APP).label
    lines = [
        (
            f"| App | Span | Months | Reviews | Mean score (95% CI) | 1★ | Replied "
            f"| {ref}: mean score | {ref}: 1★ |"
        ),
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in periods[periods["version"] == version].iterrows():
        ref_row = pd.Series({k[4:]: v for k, v in r.items() if k.startswith("ref_")})
        lines.append(
            f"| {by_key(r['app_key']).label} | {r['span']} | {r['start']} to {r['end']} "
            f"| {r['n']:,} | {fmt_mean(r)} | {fmt_share(r['share_1_star'], r['n'])} "
            f"| {fmt_share(r['reply_rate'], r['n'])} | {fmt_mean(ref_row)} "
            f"| {fmt_share(ref_row['share_1_star'], ref_row['n'])} |"
        )
    return "\n".join(lines)


def monthly_markdown(series: pd.DataFrame, version: str) -> str:
    """Months as rows; per app: reviews, mean score, share of 1★, reply rate."""
    frame = series[series["version"] == version]
    header = ["Month"]
    for app in APP_ORDER:
        label = by_key(app).label
        header += [f"{label} n", f"{label} mean", f"{label} 1★", f"{label} replied"]
    lines = ["| " + " | ".join(header) + " |", "|---|" + "---:|" * (len(header) - 1)]
    indexed = frame.set_index(["month", "app_key"])
    for month in sorted(frame["month"].unique()):
        cells = [str(month)]
        for app in APP_ORDER:
            if (month, app) not in indexed.index:
                cells += ["–"] * 4
                continue
            r = indexed.loc[(month, app)]
            cells += [
                str(r["n"]),
                f"{r['mean_score']:.2f}",
                f"{r['share_1_star']:.0%}",
                f"{r['reply_rate']:.0%}",
            ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render(reviews: pd.DataFrame, series: pd.DataFrame, periods: pd.DataFrame) -> str:
    edited = int(reviews["likely_edited"].astype(bool).sum())
    return f"""# Ratings around the reply-policy changes (stage D1b)

Generated by `python -m support_reply_gap.analysis.policy_change_report`. Do not edit
by hand.

Descriptive only. The companies chose when to start or stop replying, and other things
changed at the same time: app releases, pricing, the user base, the news. Nothing here
says what replying does to ratings. {by_key(REFERENCE_APP).label} is a reference series,
not a control.

**Population.** {len(reviews):,} Google Play reviews of all star ratings, dated
{FIRST_MONTH} to {LAST_MONTH} by the month of `posted_at`. 2026-11 is left out because
the scrape ended on the 3rd.

**Events**, dated by the month replies were written and fixed in `docs/build-order.md`
before any rating series was drawn:

{events_text()}

**Edited reviews.** Google Play keeps only a review's latest version, so a review edited
after a reply carries the edit's date and score. {edited:,} reviews are detectably edited
(a reply timestamped before the review). Edits are detectable only when a reply exists,
so more replies mean more detectable edits; the edited share is not an outcome. Every
figure below is given with and without the detectable ones. Undetectable edits remain
in both.

![Ratings around the reply-policy changes]({CHART_PATH.name})

## Per period: all reviews

{period_markdown(periods, ALL)}

## Per period: without edited reviews

{period_markdown(periods, WITHOUT_EDITED)}

## Per month: all reviews

{monthly_markdown(series, ALL)}

## Per month: without edited reviews

{monthly_markdown(series, WITHOUT_EDITED)}

## Caveats

- The 95% interval of a mean score covers sampling noise among the reviews written,
  not who chooses to write one. Review writers are not a sample of users.
- N26's span before its first event is one month. Its "paused" span follows a
  two-month burst of replies, so it is not a clean "never replied" baseline either.
- C24's replies rose gradually from 2026-01; its "replying" span mixes months with
  low and high reply rates.
- Text reviews only: star-only ratings are not returned by the review endpoint.
"""


def main() -> None:
    reviews = load_monthly_input()
    series = monthly(reviews)
    periods = period_table(reviews)
    subtitle = (
        f"Google Play reviews, all star ratings, {FIRST_MONTH} to {LAST_MONTH} · "
        "events dated by when replies were written · descriptive only"
    )
    plot_policy_change(series, CHART_PATH, subtitle)
    REPORT_PATH.write_text(render(reviews, series, periods))
    print(f"wrote {REPORT_PATH.relative_to(ROOT)} and {CHART_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
