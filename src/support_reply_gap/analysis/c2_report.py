"""C2 report: label the population, build the reply table, write markdown and chart.

    python -m support_reply_gap.analysis.c2_report

Writes reports/reply_gap_c2.md and reports/reply_gap_c2.png. Everything in them is
generated; the interpretation lives in the README, where re-running cannot overwrite it.
"""

from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

from support_reply_gap.analysis.reply_gap import (
    ALL_APPS,
    ALL_REVIEWS,
    MAX_STARS,
    SMALL_CELL,
    label_population,
    load_population,
    reply_table,
)
from support_reply_gap.analysis.reply_gap_chart import plot_reply_gap
from support_reply_gap.apps import by_key
from support_reply_gap.models.baseline import CHOSEN
from support_reply_gap.models.data import load_gold

ROOT = Path(__file__).resolve().parents[3]
REPORT_PATH = ROOT / "reports/reply_gap_c2.md"
CHART_PATH = ROOT / "reports/reply_gap_c2.png"

# Validation macro-F1 of CHOSEN, from C1. Stated in the report so no reader takes the
# labels for ground truth.
BASELINE_VAL_MACRO_F1 = 0.486


def fmt_rate(rate: float, n: int, small: bool) -> str:
    """'58% (219)'; italic when the cell is too small to interpret."""
    if n == 0 or math.isnan(rate):
        return "–"
    text = f"{rate:.0%} ({n})"
    return f"*{text}*" if small else text


def fmt_latency(hours: float, n: int) -> str:
    """Minutes under an hour, days from two days on, so all three apps stay readable."""
    if n == 0 or math.isnan(hours):
        return "–"
    if hours < 1:
        value = f"{hours * 60:.0f} min"
    elif hours < 48:
        value = f"{hours:.1f} h"
    else:
        value = f"{hours / 24:.1f} d"
    text = f"{value} ({n})"
    return f"*{text}*" if n < SMALL_CELL else text


def grid(table: pd.DataFrame, cell) -> pd.DataFrame:
    """Labels as rows (reference row first, then most common), apps as columns."""
    pooled = table[(table["app_key"] == ALL_APPS) & (table["label"] != ALL_REVIEWS)]
    labels = [ALL_REVIEWS, *pooled.sort_values("n", ascending=False)["label"]]
    apps = [a for a in table["app_key"].unique() if a != ALL_APPS] + [ALL_APPS]
    indexed = table.set_index(["label", "app_key"])
    out = pd.DataFrame(
        [[cell(indexed.loc[(label, app)]) for app in apps] for label in labels],
        index=labels,
        columns=[by_key(a).label if a != ALL_APPS else "All apps" for a in apps],
    )
    return out


def markdown_table(frame: pd.DataFrame, first_header: str = "Label") -> str:
    # written by hand: pandas' to_markdown needs the extra `tabulate` package
    header = [first_header, *frame.columns]
    lines = [
        "| " + " | ".join(header) + " |",
        "|---|" + "---:|" * len(frame.columns),
    ]
    for label, row in frame.iterrows():
        name = label if label == ALL_REVIEWS else f"`{label}`"
        lines.append("| " + " | ".join([name, *row]) + " |")
    return "\n".join(lines)


def render(labelled: pd.DataFrame, table: pd.DataFrame, chart_name: str) -> str:
    first = labelled["posted_at"].min().date()
    last = labelled["posted_at"].max().date()
    n_training = int(labelled["in_training"].sum())

    rates = grid(table, lambda r: fmt_rate(r["reply_rate"], r["n"], r["small"]))
    latency = grid(table, lambda r: fmt_latency(r["median_latency_h"], r["n_latency"]))
    held_out = grid(
        table,
        lambda r: fmt_rate(r["reply_rate_held_out"], r["n_held_out"], r["n_held_out"] < SMALL_CELL),
    )
    stars = grid(table, lambda r: "–" if r["n"] == 0 else f"{r['share_1_star']:.0%}")
    by_star = labelled.groupby("score")["has_reply"].mean()

    return f"""# Reply gap: first end-to-end answer (stage C2)

Generated by `python -m support_reply_gap.analysis.c2_report`. Do not edit by hand.

Descriptive only. Which reviews receive a reply is each company's choice, and that
choice is unobserved. Nothing here says why a complaint type is or is not answered.

**Population.** {len(labelled):,} Google Play reviews rated 1–{MAX_STARS}★, posted
{first} to {last}, after the B3 cleaning rules (German or uncertain language, not a
single word), repeated texts kept.

**Labels.** Predicted by the C1 baseline (TF-IDF + logistic regression, C = {CHOSEN["C"]:g},
threshold {CHOSEN["threshold"]}), validation macro-F1 {BASELINE_VAL_MACRO_F1:.3f}. Trained on the
240 train and validation reviews of the gold set; {n_training} of those fall in this
population. A review with several labels counts once in each.

![Reply rate by complaint label, relative to each app's average]({chart_name})

## Reply rate

Share of reviews with a reply, with the number of reviews in brackets. *Italic*: fewer
than {SMALL_CELL} reviews, not to be interpreted.

{markdown_table(rates)}

## Median reply latency

Among replied reviews whose latency is known (edited reviews have none), count in
brackets. *Italic*: fewer than {SMALL_CELL}.

{markdown_table(latency)}

## Share of 1★ reviews

In this population 1★ reviews receive a reply more often ({by_star[1]:.0%}) than 2★
({by_star[2]:.0%}) and 3★ ({by_star[3]:.0%}). A label with a high share of 1★ reviews can
show a higher reply rate for that reason alone.

{markdown_table(stars)}

## Check: reply rate without the training reviews

The same reply rates without the {n_training} reviews the model was trained on, whose
labels mostly repeat the human ones. Close agreement with the first table means
those reviews do not drive the pattern.

{markdown_table(held_out)}

## Caveats

- The labels are model predictions at validation macro-F1 {BASELINE_VAL_MACRO_F1:.2f}, not
  human labels. `performance` and `crash_stability` were under-predicted on
  validation, so their counts here are likely too low.
- 4–5★ reviews are left out: on them the baseline assigns complaint labels to about
  half of all 5★ reviews, which looks implausible. The gold set holds 21 5★ reviews.
- App and star rating vary the reply rate more than the label does. Label differences
  are compared within an app; the "All apps" column mixes apps and is shown for
  completeness only.
- N26 replies to nearly every 1–3★ review, so its reply rates cannot separate labels.
"""


def main() -> None:
    labelled = label_population(load_population(), load_gold())
    table = reply_table(labelled)
    subtitle = (
        f"1–{MAX_STARS}★ Google Play reviews · labels predicted by the C1 baseline "
        f"(validation macro-F1 {BASELINE_VAL_MACRO_F1:.2f}) · descriptive only"
    )
    plot_reply_gap(table, CHART_PATH, subtitle)
    REPORT_PATH.write_text(render(labelled, table, CHART_PATH.name))
    print(f"wrote {REPORT_PATH.relative_to(ROOT)} and {CHART_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
